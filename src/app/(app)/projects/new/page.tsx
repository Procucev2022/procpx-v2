'use client';
// app/(app)/projects/new/page.tsx - Standardised Create Project Workspace
import { useState, useEffect } from 'react';
import { reportHandledClientFailure } from '@/lib/observability/client-reporter';
import { useRouter } from 'next/navigation';
import Link from 'next/link';
import { AlertTriangle, ShieldAlert } from 'lucide-react';
import PageHeader from '@/components/ui/PageHeader';
import FormSection from '@/components/ui/FormSection';
import { SECTORS, PROJECT_TYPES, CURRENCIES } from "./page.constants";
import { UI_STRINGS } from "@/lib/ui-strings.constants";
import { interpolateUiString } from "@/lib/i18n";



export default function NewProjectPage() {
  const router = useRouter();
  const [error, setError] = useState('');
  const [loading, setLoading] = useState(false);
  const [currentUserRole, setCurrentUserRole] = useState<string>('');
  const [form, setForm] = useState({
    name: '', description: '', sector: '', projectType: '',
    location: '', address: '', city: '', state: '', country: 'India',
    areaSqFt: '', costCentre: '', projectOwner: '',
    budget: '', currency: 'INR', businessUnit: '',
    numberOfFloors: '', numberOfUnits: '',
    startDate: '', targetCompletion: '',
  });

  useEffect(() => {
    fetch('/api/auth/me')
      .then(r => r.json())
      .then(d => {
        const role = d.data?.user?.role || d.user?.role || '';
        setCurrentUserRole(role);
      })
      .catch((error: unknown) => reportHandledClientFailure(error, {
        operation: 'load_project_creation_role', route: '/api/auth/me',
      }));
  }, []);

  const canCreate = !currentUserRole || ['SUPER_ADMIN', 'CLIENT_ADMIN', 'PROJECT_USER'].includes(currentUserRole);

  function update(field: string, value: string) {
    setForm(f => ({ ...f, [field]: value }));
  }

  async function handleSubmit(e: React.FormEvent) {
    e.preventDefault();
    setError('');
    if (currentUserRole && !canCreate) {
      return setError(UI_STRINGS.appAppProjectsNewPage.forbiddenYourRoleDoesNotHavePermissionToCreateProjects);
    }
    if (!form.name.trim()) return setError(UI_STRINGS.common.projectNameIsRequired);
    if (!form.sector) return setError(UI_STRINGS.common.sectorIsRequired);
    if (!form.projectType) return setError(UI_STRINGS.common.projectTypeIsRequired);

    setLoading(true);
    try {
      const res = await fetch('/api/projects', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(form),
      });
      let data: any = null;
      try {
        data = await res.json();
      } catch {
        // Fallback if response is empty or non-JSON
      }
      if (!res.ok) {
        setError(interpolateUiString(UI_STRINGS.common.value1, { "value1": data?.error || interpolateUiString(UI_STRINGS.common.userMessages.failedToCreateProjectHttpPleaseCheckDetailsAndRetry, { "status": res.status }) }));
        return;
      }
      if (data?.id) {
        router.push(`/projects/${data.id}`);
      } else {
        router.push('/projects');
      }
    } catch (err: any) {
      console.error('[Create Project Network Error]:', err);
      setError(interpolateUiString(UI_STRINGS.common.value1, { "value1": err?.message || UI_STRINGS.common.userMessages.aNetworkErrorOccurredWhileConnectingToTheServerPleaseTryAgain }));
    } finally {
      setLoading(false);
    }
  }

  return (
    <div className="w-full max-w-5xl mx-auto">
      <PageHeader
        title={UI_STRINGS.appAppProjectsNewPage.createNewProject}
        subtitle={UI_STRINGS.appAppProjectsNewPage.projectIDWillBeAutoGeneratedInStandardFormatCPXPXXXXXX}
        backHref="/projects"
        backLabel="Back to Projects"
      />

      {currentUserRole && !canCreate && (
        <div className="p-3.5 mb-6 rounded-lg bg-amber-50 border border-amber-200 text-amber-900 text-sm flex items-center gap-2.5">
          <ShieldAlert size={18} className="text-amber-600 shrink-0" />
          <span>
            <strong>{UI_STRINGS.appAppProjectsNewPage.readOnlyNotice}</strong>{UI_STRINGS.appAppProjectsNewPage.yourCurrentRole}<code>{currentUserRole}</code>{UI_STRINGS.appAppProjectsNewPage.hasReadOnlyAccessToProjectsOnlyProjectUsersAndAdministratorsCanCreateProjects}</span>
        </div>
      )}

      {error && (
        <div className="p-3.5 mb-6 rounded-lg bg-rose-50 border border-rose-200 text-rose-900 text-sm flex items-center gap-2.5">
          <AlertTriangle size={18} className="text-rose-600 shrink-0" />
          <span>{error}</span>
        </div>
      )}

      <form onSubmit={handleSubmit} className="space-y-6">
        {/* Section 1: Basic Information */}
        <FormSection
          sectionNumber="1"
          title={UI_STRINGS.common.basicInformation}
          subtitle={UI_STRINGS.appAppProjectsNewPage.defineCoreProjectIdentifiersIndustrySectorAndOperationalScope}
        >
          <div className="space-y-4">
            <div className="form-field">
              <label className="form-label text-xs font-semibold text-slate-700">{UI_STRINGS.common.projectName}<span className="text-rose-600 font-bold">{UI_STRINGS.common.copyd1yn99}</span>
              </label>
              <input
                className="input h-[40px] text-sm w-full"
                value={form.name}
                onChange={e => update('name', e.target.value)}
                placeholder={UI_STRINGS.appAppProjectsNewPage.eGPremiumRetailStoreBengaluruFlagship}
                required
              />
            </div>

            <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
              <div className="form-field">
                <label className="form-label text-xs font-semibold text-slate-700">{UI_STRINGS.common.sector}<span className="text-rose-600 font-bold">{UI_STRINGS.common.copyd1yn99}</span>
                </label>
                <select
                  className="input h-[40px] text-sm w-full cursor-pointer"
                  value={form.sector}
                  onChange={e => update('sector', e.target.value)}
                  required
                >
                  <option value="">{UI_STRINGS.appAppProjectsNewPage.selectSector}</option>
                  {SECTORS.map(s => <option key={s} value={s}>{s}</option>)}
                </select>
              </div>

              <div className="form-field">
                <label className="form-label text-xs font-semibold text-slate-700">{UI_STRINGS.appAppProjectsNewPage.projectType}<span className="text-rose-600 font-bold">{UI_STRINGS.common.copyd1yn99}</span>
                </label>
                <select
                  className="input h-[40px] text-sm w-full cursor-pointer"
                  value={form.projectType}
                  onChange={e => update('projectType', e.target.value)}
                  required
                >
                  <option value="">{UI_STRINGS.appAppProjectsNewPage.selectType}</option>
                  {PROJECT_TYPES.map(t => <option key={t} value={t}>{t.replace(/_/g, ' ')}</option>)}
                </select>
              </div>
            </div>

            <div className="form-field">
              <label className="form-label text-xs font-semibold text-slate-700">{UI_STRINGS.appAppProjectsNewPage.projectDescriptionScopeSummary}</label>
              <textarea
                className="input h-auto min-h-[90px] py-2 text-sm w-full"
                value={form.description}
                onChange={e => update('description', e.target.value)}
                placeholder={UI_STRINGS.appAppProjectsNewPage.briefDescriptionOfTheCapexScopeKeyMilestonesAndBusinessObjectives}
                rows={3}
              />
            </div>
          </div>
        </FormSection>

        {/* Section 2: Location */}
        <FormSection
          sectionNumber="2"
          title={UI_STRINGS.appAppProjectsNewPage.locationSiteAddress}
          subtitle={UI_STRINGS.appAppProjectsNewPage.geographicParametersForRegionalCostCentreAlignmentAndDeliveryLogistics}
        >
          <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
            <div className="form-field">
              <label className="form-label text-xs font-semibold text-slate-700">{UI_STRINGS.common.city}</label>
              <input
                className="input h-[40px] text-sm w-full"
                value={form.city}
                onChange={e => update('city', e.target.value)}
                placeholder={UI_STRINGS.common.bengaluru}
              />
            </div>

            <div className="form-field">
              <label className="form-label text-xs font-semibold text-slate-700">{UI_STRINGS.common.stateRegion}</label>
              <input
                className="input h-[40px] text-sm w-full"
                value={form.state}
                onChange={e => update('state', e.target.value)}
                placeholder={UI_STRINGS.appAppProjectsNewPage.karnataka}
              />
            </div>

            <div className="form-field">
              <label className="form-label text-xs font-semibold text-slate-700">{UI_STRINGS.appAppProjectsNewPage.country}</label>
              <input
                className="input h-[40px] text-sm w-full"
                value={form.country}
                onChange={e => update('country', e.target.value)}
              />
            </div>

            <div className="form-field">
              <label className="form-label text-xs font-semibold text-slate-700">{UI_STRINGS.appAppProjectsNewPage.locationCommercialArea}</label>
              <input
                className="input h-[40px] text-sm w-full"
                value={form.location}
                onChange={e => update('location', e.target.value)}
                placeholder={UI_STRINGS.appAppProjectsNewPage.eGKoramangala5thBlock}
              />
            </div>

            <div className="form-field md:col-span-2">
              <label className="form-label text-xs font-semibold text-slate-700">{UI_STRINGS.appAppProjectsNewPage.fullSiteAddress}</label>
              <input
                className="input h-[40px] text-sm w-full"
                value={form.address}
                onChange={e => update('address', e.target.value)}
                placeholder={UI_STRINGS.appAppProjectsNewPage.plotUnitNumberStreetLandmarkPinCode}
              />
            </div>
          </div>
        </FormSection>

        {/* Section 3: Commercial & Project Details */}
        <FormSection
          sectionNumber="3"
          title={UI_STRINGS.appAppProjectsNewPage.commercialTechnicalSpecifications}
          subtitle={UI_STRINGS.appAppProjectsNewPage.fitoutFloorAreaCostCentreMappingInitialBudgetAndPhysicalLayout}
        >
          <div className="grid grid-cols-1 md:grid-cols-3 gap-4">
            <div className="form-field">
              <label className="form-label text-xs font-semibold text-slate-700">{UI_STRINGS.common.areaSqFt}</label>
              <input
                className="input h-[40px] text-sm w-full font-mono"
                type="number"
                value={form.areaSqFt}
                onChange={e => update('areaSqFt', e.target.value)}
                placeholder={UI_STRINGS.appAppProjectsNewPage.copyvka61c}
              />
            </div>

            <div className="form-field">
              <label className="form-label text-xs font-semibold text-slate-700">{UI_STRINGS.appAppProjectsNewPage.costCentreCode}</label>
              <input
                className="input h-[40px] text-sm w-full font-mono"
                value={form.costCentre}
                onChange={e => update('costCentre', e.target.value)}
                placeholder={UI_STRINGS.appAppProjectsNewPage.rETBLR001}
              />
            </div>

            <div className="form-field">
              <label className="form-label text-xs font-semibold text-slate-700">{UI_STRINGS.appAppProjectsNewPage.projectOwner}</label>
              <input
                className="input h-[40px] text-sm w-full"
                value={form.projectOwner}
                onChange={e => update('projectOwner', e.target.value)}
                placeholder={UI_STRINGS.appAppProjectsNewPage.nameOrFunctionalLead}
              />
            </div>

            <div className="form-field">
              <label className="form-label text-xs font-semibold text-slate-700">{UI_STRINGS.appAppProjectsNewPage.budgetEst}</label>
              <input
                className="input h-[40px] text-sm w-full font-mono"
                type="number"
                value={form.budget}
                onChange={e => update('budget', e.target.value)}
                placeholder={UI_STRINGS.common.copywwhtor}
              />
            </div>

            <div className="form-field">
              <label className="form-label text-xs font-semibold text-slate-700">{UI_STRINGS.common.currency}</label>
              <select
                className="input h-[40px] text-sm w-full cursor-pointer font-mono"
                value={form.currency}
                onChange={e => update('currency', e.target.value)}
              >
                {CURRENCIES.map(c => <option key={c} value={c}>{c}</option>)}
              </select>
            </div>

            <div className="form-field">
              <label className="form-label text-xs font-semibold text-slate-700">{UI_STRINGS.appAppProjectsNewPage.businessUnit}</label>
              <input
                className="input h-[40px] text-sm w-full"
                value={form.businessUnit}
                onChange={e => update('businessUnit', e.target.value)}
                placeholder={UI_STRINGS.appAppProjectsNewPage.eGRetailOperations}
              />
            </div>

            <div className="form-field">
              <label className="form-label text-xs font-semibold text-slate-700">{UI_STRINGS.appAppProjectsNewPage.numberOfFloors}</label>
              <input
                className="input h-[40px] text-sm w-full font-mono"
                type="number"
                value={form.numberOfFloors}
                onChange={e => update('numberOfFloors', e.target.value)}
                placeholder={UI_STRINGS.common.copyefwnq4}
              />
            </div>

            <div className="form-field md:col-span-2">
              <label className="form-label text-xs font-semibold text-slate-700">{UI_STRINGS.appAppProjectsNewPage.numberOfUnitsOutlets}</label>
              <input
                className="input h-[40px] text-sm w-full font-mono"
                type="number"
                value={form.numberOfUnits}
                onChange={e => update('numberOfUnits', e.target.value)}
                placeholder={UI_STRINGS.common.copyefwnq4}
              />
            </div>
          </div>
        </FormSection>

        {/* Section 4: Timeline */}
        <FormSection
          sectionNumber="4"
          title={UI_STRINGS.appAppProjectsNewPage.projectTimeline}
          subtitle={UI_STRINGS.appAppProjectsNewPage.targetStartAndCompletionScheduleForProcurementPlanning}
        >
          <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
            <div className="form-field">
              <label className="form-label text-xs font-semibold text-slate-700">{UI_STRINGS.appAppProjectsNewPage.projectStartDate}</label>
              <input
                className="input h-[40px] text-sm w-full cursor-pointer"
                type="date"
                value={form.startDate}
                onChange={e => update('startDate', e.target.value)}
              />
            </div>

            <div className="form-field">
              <label className="form-label text-xs font-semibold text-slate-700">{UI_STRINGS.appAppProjectsNewPage.targetCompletionDate}</label>
              <input
                className="input h-[40px] text-sm w-full cursor-pointer"
                type="date"
                value={form.targetCompletion}
                onChange={e => update('targetCompletion', e.target.value)}
              />
            </div>
          </div>
        </FormSection>

        {/* Actions bar */}
        <div className="flex items-center justify-end gap-3 pt-4 border-t border-slate-200">
          <Link
            href="/projects"
            className="btn btn-secondary h-[42px] px-5 text-sm font-semibold inline-flex items-center"
          >{UI_STRINGS.common.cancel}</Link>
          <button
            type="submit"
            className="btn btn-primary h-[42px] px-6 text-sm font-bold inline-flex items-center gap-2 shadow-xs"
            disabled={loading || Boolean(currentUserRole && !canCreate)}
          >
            {loading ? (
              <>
                <div className="w-4 h-4 border-2 border-white border-t-transparent rounded-full animate-spin" />
                <span>{UI_STRINGS.appAppProjectsNewPage.creatingProject}</span>
              </>
            ) : (
              UI_STRINGS.appAppProjectsNewPage.createProject
            )}
          </button>
        </div>
      </form>
    </div>
  );
}

